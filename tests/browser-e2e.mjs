import {chromium} from "playwright";
import assert from "node:assert/strict";

const base=process.env.BASE_URL || "http://127.0.0.1:8787";
const browser=await chromium.launch({headless:true});
try{
  const page=await browser.newPage({viewport:{width:1280,height:900},acceptDownloads:true});
  await page.goto(base+"/#studio",{waitUntil:"networkidle"});
  await page.locator("#tradeTabs button").first().waitFor();
  await page.locator("#task").selectOption("heatpump");
  await page.locator("#useCustomRates").check();
  await page.locator("#customHours").fill("10");
  await page.locator("#customRate").fill("100");
  await page.locator("#customMaterials").fill("500");
  await page.locator("#customOverhead").fill("20");
  await page.locator("#customMarkup").fill("25");
  await page.locator("#savePricebook").click();
  await page.locator("#calculateButton").click();
  await page.locator("#quoteMedian").getByText("$2,250").waitFor();
  assert.match(await page.locator("#pricingDisclosure").innerText(),/your entered job rates/);
  await page.locator("#saveQuote").click();
  await page.goto(base+"/#estimates");
  assert.match(await page.locator("#estimatesBody").innerText(),/2,250/);
  await page.reload({waitUntil:"networkidle"});
  assert.match(await page.locator("#estimatesBody").innerText(),/2,250/);
  await page.goto(base+"/#studio");
  await page.locator("#task").selectOption("heatpump");
  assert.equal(await page.locator("#useCustomRates").isChecked(),true);
  assert.equal(await page.locator("#customRate").inputValue(),"100");
  await page.locator("#customRate").fill("");
  await page.locator("#calculateButton").click();
  assert.match(await page.locator("#quoteError").innerText(),/laborRate/);
  const dlPromise=page.waitForEvent("download");
  await page.goto(base+"/#estimates");
  await page.locator("#exportCsv").click();
  const dl=await dlPromise;
  assert.match(dl.suggestedFilename(),/\.csv$/);
  await page.goto(base+"/#settings");
  const backupPromise=page.waitForEvent("download");
  await page.locator("#exportJson").click();
  const backupDownload=await backupPromise;
  const {readFileSync}=await import("node:fs");
  const backup=JSON.parse(readFileSync(await backupDownload.path(),"utf8"));
  assert.equal(backup.version,3);
  assert.equal(backup.pricebook["hvac:heatpump"].laborRate,100);
  await page.goto(base+"/#studio");
  await page.locator("#task").selectOption("heatpump");
  await page.locator("#clearPricebook").click();
  assert.equal(await page.locator("#useCustomRates").isChecked(),false);
  await page.goto(base+"/#settings");
  await page.locator("#importJson").setInputFiles({name:"autoquoter-test-backup.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(backup))});
  await page.locator("#toast").getByText(/job rate presets/).waitFor();
  await page.goto(base+"/#studio");
  await page.locator("#task").selectOption("heatpump");
  assert.equal(await page.locator("#useCustomRates").isChecked(),true);
  assert.equal(await page.locator("#customRate").inputValue(),"100");
  await page.goto(base+"/pricing-guide.html");
  await page.locator("#mkPrice").getByText("$3,653.28").waitFor();
  await page.locator("#mkMarkup").fill("0");
  await page.locator("#mkPrice").getByText("$3,044.40").waitFor();
  await page.goto(base+"/custom-setup.html");
  assert.match(await page.title(),/Custom Contractor/);
  await page.goto(base+"/sitemap.xml");
  assert.match(await page.locator("body").innerText(),/pricing-guide.html/);

  // Real Cloudflare local Durable Object test: private lead intake and self-deletion.
  await page.goto(base+"/custom-setup.html");
  await page.locator("#leadEmail").fill("demo-buyer@example.org");
  await page.locator("#leadProblem").fill("I would like a faster way to configure five common job pricebooks using my own labor and material costs.");
  await page.locator("#leadBudget").selectOption("200to500");
  await page.locator("#leadConsent").check();
  await page.locator("#leadSubmit").click();
  await page.locator("#leadReceipt").waitFor({state:"visible"});
  const reference=await page.locator("#leadReference").textContent();
  assert.match(reference,/^[a-f0-9-]{36}:[a-f0-9]{32}$/);
  await page.goto(base+"/lead-delete.html");
  await page.locator("#deleteRef").fill(reference);
  await page.locator("#deleteForm button").click();
  await page.locator("#deleteStatus").getByText(/processed/).waitFor();
  const notAdmin=await page.request.get(base+"/api/leads/admin");
  assert.equal(notAdmin.status(),403);

  console.log("BROWSER_E2E_OK: custom pricing, saved pricebook, calculate, invalid input, persistence, CSV, pricing calculator, SEO pages, private inquiry and deletion");
}finally{await browser.close();}
